export type Key = keyof typeof fr;
export type Dictionary = typeof fr;

/** French typography: a narrow no-break space before « : ; ? ! » and inside « », so a sign never
 *  wraps onto its own line (phones, U10). */
function typeset(dictionary: typeof fr): typeof fr {
  const nbsp = '\u202f';
  const fix = (text: string) => text.replace(/ ([:;?!»])/g, `${nbsp}$1`).replace(/« /g, `«${nbsp}`);
  return Object.fromEntries(Object.entries(dictionary).map(([k, v]) => [k, fix(v)])) as typeof fr;
}

const dictionaries: Record<Language, typeof fr> = { fr: typeset(fr), de, it };

export const LanguageContext = createContext<Language>('fr');

/** The office's language. */
export function useLanguage(): Language {
  return useContext(LanguageContext);
}

export function useT() {
  const language = useContext(LanguageContext);
  return (key: Key) => dictionaries[language][key];
}

/** A counted word, singular for one (« 1 cheval », « 2 chevaux »): `key`'s `_one` form when it
 *  has one. */
export function usePlural() {
  const language = useContext(LanguageContext);
  return (n: number, key: Key) => {
    const words = dictionaries[language] as Record<string, string>;
    return (n === 1 ? words[`${key}_one`] : undefined) ?? words[key];
  };
}

/** Why out of a class (Swiss Equestrian's name: `ausgeschieden`, `aufgegeben`…) in the office's
 *  language; a reason the app does not know as Swiss Equestrian names it. */
export function useReason() {
  const language = useContext(LanguageContext);
  return (name: string) => (dictionaries[language] as Record<string, string>)[`reason_${name}`] ?? name;
}

/** A change's name in the office's language (`command`: the core's command name). */
export function useChangeName() {
  const language = useContext(LanguageContext);
  return (command: string) => (dictionaries[language] as Record<string, string>)[`change_${command}`] ?? command;
}

export function formatDate(date: string, language: Language): string {
  if (!date) return '';
  const d = new Date(`${date.slice(0, 10)}T12:00:00`);
  const text = d.toLocaleDateString(`${language}-CH`, { weekday: 'long', day: 'numeric', month: 'long' });
  return text.charAt(0).toUpperCase() + text.slice(1);
}

/** A day in short: "sa 5.7." (the weekday and the date). */
export function formatDayShort(date: string, language: Language): string {
  if (!date) return '';
  const d = new Date(`${date.slice(0, 10)}T12:00:00`);
  const weekday = d.toLocaleDateString(`${language}-CH`, { weekday: 'short' }).replace('.', '');
  return `${weekday} ${d.getDate()}.${d.getMonth() + 1}.`;
}

export function formatMillis(millis: number, language: Language): string {
  return new Date(millis).toLocaleString(`${language}-CH`, { day: 'numeric', month: 'short', hour: '2-digit', minute: '2-digit' });
}
