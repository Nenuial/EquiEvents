#!/usr/bin/env node
// Write corpus/SUMMARY.md: what the corpus covers and how much of it Rosson reproduces.
// Reads corpus/<nr>/snapshot.json, source.json and oracle.json (run check-corpus first).

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const corpusDir = join(dirname(fileURLToPath(import.meta.url)), '../corpus');
const read = (nr, f) => JSON.parse(readFileSync(join(corpusDir, nr, f), 'utf8'));
const events = readdirSync(corpusDir).filter(d => /^\d{4}\.\d+$/.test(d)).sort();

const pct = (a, b) => (b ? `${Math.round((100 * a) / b)} %` : '–');
const lines = ['# Golden corpus — summary', '',
  'Generated by `golden/src/summarize.mjs`. "Reproduced" = Rosson 3.3.15, started from the entered',
  'values only (all computed fields removed), stores exactly what Rosson stored at the show.', ''];

lines.push('## Shows', '', '| Show | Rosson at show | Snapshot | Prüfungen | Results | Reproduced |', '|---|---|---|---:|---:|---:|');
const byTable = new Map();
let allTables = [];
let total = { results: 0, identical: 0 };
for (const nr of events) {
  const s = read(nr, 'snapshot.json');
  const src = read(nr, 'source.json');
  const oracle = existsSync(join(corpusDir, nr, 'oracle.json')) ? read(nr, 'oracle.json') : null;
  allTables = s.wertungen;
  lines.push(`| ${nr} | ${src.chosen.rosson} | ${src.chosen.file.split('/').pop()} | ${s.pruefungen.length} | ${s.resultate.length} | ${oracle ? `${oracle.identical}/${oracle.results} (${pct(oracle.identical, oracle.results)})` : 'not checked'} |`);
  if (oracle) { total.results += oracle.results; total.identical += oracle.identical; }

  const disziplin = Object.fromEntries(s.disziplinen.map(d => [d.id, d.code]));
  const ap = Object.fromEntries(s.ausschreibung_pruefungen.map(a => [a.id, a]));
  for (const p of s.pruefungen) {
    const a = ap[p.ausschreibung_pruefung_id] || {};
    const code = disziplin[a.disziplin_id] || '?';
    const w = s.wertungen.find(x => x.id === p.wertung_id);
    const key = code === 'CD' ? 'CD · Dressur (Programm-basiert)' : `${code} · ${w ? `${w.id} ${w.bezeichnung_de}` : 'ohne Wertung'}`;
    const o = oracle?.perPruefung[String(p.id)];
    const e = byTable.get(key) || { pruefungen: 0, results: 0, identical: 0, teams: 0, shows: new Set(), diffs: {} };
    e.pruefungen++; e.shows.add(nr);
    if ((p.equipen || []).length) e.teams++;
    if (o) {
      e.results += o.results; e.identical += o.identical;
      for (const [f, x] of Object.entries(o.fields)) e.diffs[f.replace(' (value)', '')] = (e.diffs[f.replace(' (value)', '')] || 0) + x.count;
    }
    byTable.set(key, e);
  }
}
lines.push(`| **Total** | | | | **${total.results}** | **${total.identical}/${total.results} (${pct(total.identical, total.results)})** |`, '');

lines.push('## By discipline and scoring table', '', '| Discipline · scoring table | Shows | Prüfungen (team) | Results | Reproduced | Fields that differ |', '|---|---:|---:|---:|---:|---|');
for (const [key, e] of [...byTable].sort()) {
  const diffs = Object.entries(e.diffs).map(([f, n]) => `${f} ${n}`).join(', ');
  lines.push(`| ${key} | ${e.shows.size} | ${e.pruefungen}${e.teams ? ` (${e.teams})` : ''} | ${e.results} | ${pct(e.identical, e.results)} | ${diffs} |`);
}

const used = new Set([...byTable.keys()].map(k => Number((/· (\d+) /.exec(k) || [])[1])).filter(Boolean));
const missing = allTables.filter(w => !used.has(w.id));
lines.push('', `## Scoring tables with no real data (${missing.length} of ${allTables.length})`, '',
  'These have to be covered from the Rosson code and the regulations, with hand-written test cases.', '');
for (const w of missing) lines.push(`- ${w.id} ${w.bezeichnung_de}`);
lines.push('', 'Disciplines with no real data in the corpus: driving (CA and its sub-tests), eventing / combined (CC, cross), para-dressage.', '');

writeFileSync(join(corpusDir, 'SUMMARY.md'), `${lines.join('\n')}\n`);
console.log(`Wrote corpus/SUMMARY.md (${events.length} shows, ${total.results} results, ${total.identical} reproduced)`);
