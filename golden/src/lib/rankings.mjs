// Render the results Rosson stored for an event as readable Markdown tables, one per Prüfung,
// so a person can compare them with the published result lists. Values are shown exactly as
// Rosson stored them (strings stay strings), because this file documents Rosson's output.

const md = v => (v === null || v === undefined || v === '' ? '' : String(v).replace(/\|/g, '\\|'));
const parseLenient = json => {
  if (json && typeof json === 'object') return json;
  try { return JSON.parse(json); } catch { return null; }
};

export function renderRankings(nr, s) {
  const disziplin = Object.fromEntries(s.disziplinen.map(d => [d.id, d.code]));
  const ausschreibung = Object.fromEntries(s.ausschreibung_pruefungen.map(a => [a.id, a]));
  const wertung = Object.fromEntries(s.wertungen.map(w => [w.id, w]));
  const nennung = Object.fromEntries(s.nennungen.map(n => [n.id, n]));
  const starter = Object.fromEntries(s.starter.map(x => [x.id, x]));
  const richterBuchstabe = Object.fromEntries(s.offizielle_zuweisungen.map(z => [z.id, z.buchstabe || '?']));

  const who = r => {
    if (r.equipe_id && !r.starter_id) return { nr: md(r.equipe?.startnummer), reiter: `Equipe ${r.equipe_id}`, pferd: '' };
    const n = nennung[starter[r.starter_id]?.nennung_id] || r.nennung || {};
    return {
      nr: md(n.startnummer),
      reiter: md(n.reiter_nachname),
      pferd: md((n.pferde || [])[0]?.pferdename ?? n.gastpferd_name),
      hc: n.hors_concours ? 'HC' : '',
    };
  };
  const rankOf = r => (Number.isFinite(Number(r.rang)) && r.rang !== null ? Number(r.rang) : Infinity);

  const lines = [
    `# Stored results — ${nr}`,
    '',
    'Generated by `golden/src/build-corpus.mjs` from the anonymised snapshot. Shows what Rosson',
    'stored, in its rank order. This is evidence of Rosson\'s behaviour, not a statement that it is correct.',
    '',
  ];

  const pruefungen = [...s.pruefungen].sort((a, b) => (a.position ?? 0) - (b.position ?? 0) || String(a.nummer).localeCompare(String(b.nummer), 'en', { numeric: true }));
  for (const p of pruefungen) {
    const ap = ausschreibung[p.ausschreibung_pruefung_id] || {};
    const code = disziplin[ap.disziplin_id] || '?';
    const w = wertung[p.wertung_id];
    const bewertung = w ? parseLenient(w.bewertung_json) : null;
    const results = s.resultate.filter(r => String(r.pruefung_id) === String(p.id))
      .sort((a, b) => rankOf(a) - rankOf(b) || Number(who(a).nr || 0) - Number(who(b).nr || 0));
    const starters = s.starter.filter(x => String(x.pruefung_id) === String(p.id)).length;

    lines.push(`## Prüfung ${md(p.nummer)} — ${md(p.name)}`, '');
    lines.push(`- Disziplin: ${code}${p.type ? ` (${p.type})` : ''} · Datum: ${md(String(p.datum || '').slice(0, 10))}`);
    if (w) lines.push(`- Wertung ${w.id}: ${md(w.bezeichnung_de)}${bewertung ? ` · code ${bewertung.code}` : ' · **bewertung_json is not valid JSON**'}`);
    if (p.programm_id || ap.programm_ids?.length) lines.push(`- Programm: ${md(p.programm_id ?? ap.programm_ids.join(', '))}`);
    lines.push(`- Starter: ${starters} · Resultate: ${results.length} · definitiv: ${p.definitiv ? 'ja' : 'nein'} · anzahlKlassiert: ${md(p.anzahlKlassiert)}`, '');
    if (!results.length) { lines.push('_No results stored._', ''); continue; }

    if (code === 'CD' || results[0].typ === 'dressur') {
      const judges = [...new Set(results.flatMap(r => Object.keys(r.total || {})))].filter(k => k !== 'defaultValue');
      const labels = judges.map(j => `Richter ${richterBuchstabe[j] || '?'}`);
      lines.push(`| Rang | Nr | Reiter | Pferd | ${labels.join(' | ')} | Total % | max | klassiert | Aufgabe | |`);
      lines.push(`|---:|---:|---|---|${judges.map(() => '---:').join('|')}|---:|---:|:-:|---:|---|`);
      for (const r of results) {
        const x = who(r);
        lines.push(`| ${md(r.rang)}${r.customRang ? ` (manuell ${r.customRang})` : ''} | ${x.nr} | ${x.reiter} | ${x.pferd} | ${judges.map(j => md(r.total?.[j])).join(' | ')} | ${md(r.gesamttotal)} | ${md(r.max)} | ${r.klassiert ? '✓' : ''} | ${md(r.details?.aufgabe || '')} | ${x.hc || ''}${r.duplikat ? ' duplikat' : ''} |`);
      }
    } else {
      const felder = bewertung?.sichtbare_felder || [];
      lines.push(`| Rang | Nr | Reiter | Pferd | ${felder.join(' | ')}${felder.length ? ' | ' : ''}Strafpunkte | Zeit | klassiert | Aufgabe | |`);
      lines.push(`|---:|---:|---|---|${felder.map(() => '---:|').join('')}---:|---:|:-:|---:|---|`);
      for (const r of results) {
        const x = who(r);
        lines.push(`| ${md(r.rang)}${r.customRang ? ` (manuell ${r.customRang})` : ''} | ${x.nr} | ${x.reiter} | ${x.pferd} | ${felder.map(f => md(r.details?.[f])).join(' | ')}${felder.length ? ' | ' : ''}${md(r.strafpunkte)} | ${md(r.zeit)} | ${r.klassiert ? '✓' : ''} | ${md(r.details?.aufgabe || '')} | ${x.hc || ''}${r.duplikat ? ' duplikat' : ''} |`);
      }
    }
    lines.push('');
  }
  return `${lines.join('\n')}\n`;
}
