//! Italian for the prints and exports: the Italian of each French text the prints use (the
//! prints are written in French and German, `Language::pick`); Swiss Equestrian's own Italian
//! (roles, dressage tests) comes with its data, not from here.
//!
//! A French text without Italian prints in French and is remembered, so that a test can list
//! every one (`office::italian::missing`).

use std::collections::BTreeSet;
use std::sync::Mutex;

static MISSING: Mutex<BTreeSet<(String, String)>> = Mutex::new(BTreeSet::new());

/// The Italian of a print's French text (its German alongside, to remember a missing one).
pub fn tr<'a>(fr: &'a str, de: &'a str) -> &'a str {
    // Signs and numbers only ("#", "%"): the same in Italian.
    if !fr.chars().any(char::is_alphabetic) {
        return fr;
    }
    match of(fr) {
        Some(it) => it,
        None => {
            if !fr.is_empty() {
                if let Ok(mut m) = MISSING.lock() {
                    m.insert((fr.to_string(), de.to_string()));
                }
            }
            fr
        }
    }
}

/// French texts asked in Italian without an Italian one (French, German), since the start.
pub fn missing() -> Vec<(String, String)> {
    MISSING.lock().map(|m| m.iter().cloned().collect()).unwrap_or_default()
}

